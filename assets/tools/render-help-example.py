#!/usr/bin/env python3
"""Capture the synthetic help example and generate its deterministic SVG."""
import argparse
from html import escape
import json
from pathlib import Path
import subprocess
import sys


def render_svg(text):
    lines = text.splitlines()
    if not lines or any(ord(c) < 32 and c != '\n' for c in text):
        raise ValueError('Expected nonempty plain renderer output')
    width = max(len(line) for line in lines) * 10 + 64
    height = len(lines) * 26 + 52
    rows = '\n'.join(
        f'    <text x="32" y="{42 + i * 26}" xml:space="preserve">{escape(line)}</text>'
        for i, line in enumerate(lines)
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title">\n'
        '  <title id="title">Daily Tools command help</title>\n'
        f'  <rect width="{width}" height="{height}" rx="12" fill="#161b22"/>\n'
        '  <g fill="#e6edf3" font-family="monospace" font-size="16">\n'
        f'{rows}\n  </g>\n</svg>\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Compare generated bytes without writing')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    assets = root / 'libraries/decorators/help-legend/assets'
    try:
        result = subprocess.run(
            ['nix-instantiate', '--eval', '--strict', '--json', str(assets / 'example.nix')],
            check=True, capture_output=True, text=True,
        )
        script = json.loads(result.stdout)
        if not isinstance(script, str):
            raise ValueError('Expected a generated POSIX script')
        # No command implementations or login shell: this script only prints help.
        output = subprocess.run(
            ['/bin/sh', '-s'], input=script, check=True, capture_output=True,
            text=True, cwd='/', env={'PATH': '/usr/bin:/bin', 'LC_ALL': 'C'},
        ).stdout
        products = {assets / 'images/help-legend.txt': output, assets / 'images/help-legend.svg': render_svg(output)}
        for path, text in products.items():
            data = text.encode('utf-8')
            if args.check:
                if path.read_bytes() != data:
                    raise ValueError('Generated example differs: ' + str(path.relative_to(root)))
            else:
                path.write_bytes(data)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print('Help example failed: ' + str(error), file=sys.stderr)
        return 1
    print('Help example matches the renderer.' if args.check else 'Generated text and SVG from the renderer.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
